/**
 * Refuses documentation that names something the repository does not hold.
 *
 *   bun tools/docs/check.ts
 *
 * Reads CLAUDE.md and docs/**.md, and says nothing when every path and every
 * `bun run` script they name in a code span is real.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';

import { type DocReference, deadReferences, referencesIn } from './references';

const ENTRY = 'CLAUDE.md';
const DOCS = 'docs';

function documents(): string[] {
  const found = existsSync(DOCS)
    ? readdirSync(DOCS, { recursive: true })
        .map(String)
        .filter((name) => name.endsWith('.md'))
        .map((name) => `${DOCS}/${name}`)
        .sort()
    : [];

  return [ENTRY, ...found];
}

const references: DocReference[] = documents().flatMap((document) =>
  referencesIn(document, readFileSync(document, 'utf8')),
);

/**
 * Paths git ignores are forgiven: `ios` and `android` are generated by the
 * prebuild and absent from a fresh checkout, yet the architecture document has
 * to be able to name them.
 */
const candidates = [...new Set(references.filter((r) => r.kind === 'path').map((r) => r.target))];
const ignored = new Set(
  candidates.length === 0
    ? []
    : Bun.spawnSync(['git', 'check-ignore', '--stdin'], {
        stdin: Buffer.from(candidates.join('\n')),
      })
        .stdout.toString()
        .split('\n')
        .filter((line) => line !== ''),
);

const scripts = Object.keys(JSON.parse(readFileSync('package.json', 'utf8')).scripts ?? {});

const dead = deadReferences(references, {
  holds: (path) => existsSync(path) || ignored.has(path),
  scripts,
});

for (const reference of dead) {
  const what = reference.kind === 'script' ? `bun run ${reference.target}` : reference.target;

  console.error(`${reference.document}:${reference.line}: ${what} does not exist`);
}

if (dead.length > 0) {
  console.error(`\n${dead.length} dead reference(s) in the documentation.`);
  process.exit(1);
}
