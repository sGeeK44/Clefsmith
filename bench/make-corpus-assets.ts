/**
 * Writes the module that puts the recorded corpus inside the application
 * bundle.
 *
 * Metro embeds an asset only where it can see a literal `require` of it, which
 * a loop over the manifest at run time is not. The list is therefore written
 * out, once per recording, and committed — the same arrangement as the SMuFL
 * glyph table.
 *
 *   bun bench/make-corpus-assets.ts
 *
 * Run it again whenever the corpus gains or loses a recording. `tools/verify`
 * does not: a stale list is caught by the bench refusing a manifest entry it
 * has no asset for.
 */
import { writeFile } from 'node:fs/promises';

import type { Corpus } from '@/domain/speech-corpus';

const MANIFEST = 'bench/corpus/manifest.json';
const TARGET = 'src/components/speech-bench/corpus-assets.ts';

const corpus: Corpus = await Bun.file(MANIFEST).json();
const entries = corpus.recordings
  .map(
    (recording) => `  '${recording.audio}': require('../../../bench/corpus/${recording.audio}'),`,
  )
  .join('\n');

const module = `/**
 * Every recording of the corpus, as a bundled asset.
 *
 * Generated by \`bun bench/make-corpus-assets.ts\` — do not edit. The literal
 * \`require\` calls are what makes Metro embed the files; a loop would leave the
 * bundle empty and the bench measuring nothing.
 */
import type { Corpus } from '@/domain/speech-corpus';

/**
 * The manifest, through the bundler rather than the filesystem: on a device
 * there is no repository to read it out of.
 */
export const CORPUS_MANIFEST = require('../../../bench/corpus/manifest.json') as Corpus;

export const CORPUS_ASSETS: Record<string, number> = {
${entries}
};
`;

await writeFile(TARGET, module);

console.log(`${corpus.recordings.length} recordings listed in ${TARGET}`);
